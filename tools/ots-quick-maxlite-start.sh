TOOLCHAIN
    command -v $triplet-g++ >/dev/null 2>&1 || { echo "ERROR: cross compiler $triplet-g++ not found (Debian/Ubuntu: apt install g++-$triplet)."; exit 1; }
fi
if [ -n "$toolchain_file" ]; then
    [ -r "$toolchain_file" ] || { echo "ERROR: toolchain file '$toolchain_file' not found."; exit 1; }
