            -arch)               eval $reqarg; target_arch=$1; shift;;
            -toolchain)          eval $reqarg; toolchain_file=$1; shift;;
            *)                   echo "Unknown option -$op"; do_help=1;;
        esac
    else
        aa=`echo "$1" | sed -e"s/'/'\"'\"'/g"` args="$args '$aa'"; shift
    fi
